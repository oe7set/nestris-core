// NES level palette (port of nes_palette).

type Color = [number, number, number];

export const WHITE: Color = [252, 252, 252];

export const LEVEL_PALETTE: [Color, Color][] = [
  [[0x00, 0x58, 0xf8], [0x3c, 0xbc, 0xfc]],
  [[0x00, 0xa8, 0x00], [0xb8, 0xf8, 0x18]],
  [[0xd8, 0x00, 0xcc], [0xf8, 0x78, 0xf8]],
  [[0x00, 0x58, 0xf8], [0x58, 0xd8, 0x54]],
  [[0xe4, 0x00, 0x58], [0x58, 0xf8, 0x98]],
  [[0x58, 0xf8, 0x98], [0x68, 0x88, 0xfc]],
  [[0xf8, 0x38, 0x00], [0x7c, 0x7c, 0x7c]],
  [[0x68, 0x44, 0xfc], [0xa8, 0x00, 0x20]],
  [[0x00, 0x58, 0xf8], [0xf8, 0x38, 0x00]],
  [[0xf8, 0x38, 0x00], [0xfc, 0x98, 0x38]],
];

const FALLBACK_ACCENTS: [Color, Color] = [
  [0x3c, 0xbc, 0xfc],
  [0xf8, 0x38, 0x00],
];

export const PIECE_COLORS: Record<string, Color> = {
  I: [0x00, 0xf0, 0xf0],
  O: [0xf0, 0xf0, 0x00],
  T: [0xa0, 0x00, 0xf0],
  S: [0x00, 0xf0, 0x00],
  Z: [0xf0, 0x00, 0x00],
  J: [0x00, 0x00, 0xf0],
  L: [0xf0, 0xa0, 0x00],
};

export function cellColor(level: number | null, cellId: number): Color {
  if (cellId === 2 || cellId === 3) {
    const accents =
      level === null
        ? FALLBACK_ACCENTS
        : LEVEL_PALETTE[((level % 10) + 10) % 10];
    return cellId === 2 ? accents[0] : accents[1];
  }
  return WHITE;
}

export function css([r, g, b]: Color): string {
  return `rgb(${r},${g},${b})`;
}
